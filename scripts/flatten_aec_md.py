#!/usr/bin/env python3
"""Flatten aec.md using DomainTheory's compile_md_tree with AEC as ROOT."""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

AEC_ROOT = Path(__file__).resolve().parent.parent
DT_SCRIPTS = AEC_ROOT.parent / "DomainTheory" / "scripts"
sys.path.insert(0, str(DT_SCRIPTS))

import compile_md_tree as cmt  # noqa: E402

MD_IMPORT_CITATION_BEFORE = re.compile(
    r"\*\*\[[^\]]*\]\(([^)]+\.md)\)\*\*\s*\n+(?=@import\s+\"\1\")",
    re.MULTILINE,
)

_orig_expand_import = cmt.expand_import


def expand_import_aec(
    md_path: Path,
    rel: str,
    opts: str,
    *,
    lean_mode: str,
    include_ai_prose: bool,
    cited_above: bool = False,
) -> str:
    suffix = Path(rel).suffix.lower()
    opts_norm = (opts or "").replace(" ", "")
    if suffix == ".md" and "code_block=" not in opts_norm:
        opts = f"{opts} code_block=false".strip() if opts else "code_block=false"
    chunk = _orig_expand_import(
        md_path,
        rel,
        opts,
        lean_mode=lean_mode,
        include_ai_prose=include_ai_prose,
        cited_above=cited_above,
    )
    if suffix == ".md" and "code_block=false" in (opts or "").replace(" ", ""):
        chunk = re.sub(r"^\n+# .+\n+", "\n", chunk.lstrip(), count=1)
        if Path(rel).name == "text.md":
            from normalize_aec_prose import normalize_aec_prose  # noqa: WPS433

            chunk = normalize_aec_prose(chunk)
    return chunk


def repair_inline_math_spacing(text: str) -> str:
    """OpenAI OCR often glues ``$...$`` to adjacent words; Pandoc needs spaces."""
    text = re.sub(r"(?<=[A-Za-z0-9\)\]])\$", r" $", text)
    text = re.sub(r"\$(?=[A-Za-z0-9(\[])", r"$ ", text)

    def norm_cardinality(m: re.Match[str]) -> str:
        inner = m.group(1).strip()
        return f"$\\lVert {inner}\\rVert$"

    text = re.sub(r"∥\s*([^∥]+?)\s*∥", norm_cardinality, text)
    return repair_aec_dollar_math(text)


def repair_aec_dollar_math(text: str) -> str:
    """Minimal OCR fixes so Pandoc/Markdown do not break ``$...$`` (esp. ``≤_{K}``)."""
    text = re.sub(r"≤_\{K\}", r"\\leq_K", text)
    text = re.sub(r"\\leq_\{K\}", r"\\leq_K", text)
    text = re.sub(r"\$≤_\{K\}\$", r"$\\leq_K$", text)
    text = re.sub(r"\\aleph_\{(\d+)\}", r"\\aleph_\1", text)
    text = re.sub(r"ℵ_\{(\d+)\}", r"\\aleph_\1", text)
    text = re.sub(r"i\\inI\b", r"i \\in I", text)
    text = re.sub(
        r"2\^\{κ\}\s*<\s*2\^\{κ\^\{\+\}\}",
        r"2^{\\kappa} \\lt 2^{\\kappa^+}",
        text,
    )
    text = re.sub(
        r"\(WGCH\), that is,\$\s*2\^\{\\kappa\}.*?for every infinite cardinal κ",
        r"(WGCH), that is, \\(2^{\\kappa} \\lt 2^{\\kappa^+}\\) for every infinite cardinal \\(\\kappa\\)",
        text,
    )
    text = re.sub(r"\^\{κ\}", r"^{\\kappa}", text)
    text = re.sub(r"\^\{κ\^\{\+\}\}", r"^{\\kappa^+}", text)
    text = re.sub(
        r"\$ b = ξ\^\{\|α\|\}\.\$",
        r"$b = \\xi^{|\\alpha|}$.",
        text,
    )
    text = re.sub(
        r"\$\s*b\^\{\|α\|\}\s*=\$",
        r"$b^{|\\alpha|} =$",
        text,
    )
    return text


def refresh_note_lean_imports() -> None:
    print("==> Skipping DomainTheory-only Lean @import refresh")


def install_aec_import_hooks() -> None:
    cmt.expand_import = expand_import_aec  # type: ignore[assignment]

    _orig_expand_imports = cmt.expand_imports

    def expand_imports_aec(md_path: Path, text: str, **kwargs: object) -> str:
        text = MD_IMPORT_CITATION_BEFORE.sub("", text)
        return _orig_expand_imports(md_path, text, **kwargs)  # type: ignore[arg-type]

    cmt.expand_imports = expand_imports_aec  # type: ignore[assignment]


def flatten_md_tree(
    root_md: Path,
    *,
    lean_mode: str = "link",
    include_ai_prose: bool = False,
    out_path: Path,
) -> Path:
    if not root_md.is_file():
        raise FileNotFoundError(f"missing root markdown: {root_md}")
    if lean_mode not in {"link", "inline", "omit"}:
        raise ValueError(f"unknown lean_mode: {lean_mode!r}")

    visited: set[Path] = set()
    included_lean: set[Path] = set()
    body = cmt.flatten_file(
        root_md,
        section_level=1,
        section_title=None,
        lean_mode=lean_mode,
        include_ai_prose=include_ai_prose,
        visited=visited,
        included_lean=included_lean,
    )
    body = repair_inline_math_spacing(body)
    body = cmt.ensure_model_card_markers(body)
    try:
        root_label = root_md.relative_to(AEC_ROOT).as_posix()
    except ValueError:
        root_label = root_md.as_posix()
    header = (
        "<!-- AUTO-GENERATED by scripts/flatten_aec_md.py — do not edit -->\n"
        f"<!-- Root: {root_label} "
        f"({len(visited)} notes, lean={lean_mode}, "
        f"ai_prose={'on' if include_ai_prose else 'off'}) -->\n\n"
    )
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(header + body, encoding="utf-8")
    return out_path


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--root",
        type=Path,
        default=AEC_ROOT / "aec.md",
    )
    parser.add_argument(
        "--out",
        type=Path,
        default=AEC_ROOT / ".build/aec/flatten.md",
    )
    parser.add_argument(
        "--lean",
        choices=("link", "inline", "omit"),
        default="link",
    )
    args = parser.parse_args()
    root = args.root if args.root.is_absolute() else AEC_ROOT / args.root
    out = args.out if args.out.is_absolute() else AEC_ROOT / args.out

    cmt.ROOT = AEC_ROOT
    cmt.refresh_note_lean_imports = refresh_note_lean_imports  # type: ignore[assignment]
    install_aec_import_hooks()

    flatten_md_tree(
        root,
        lean_mode=args.lean,
        out_path=out,
    )
    try:
        out_label = out.relative_to(AEC_ROOT).as_posix()
    except ValueError:
        out_label = out.as_posix()
    print(f"wrote {out_label} ({out.stat().st_size:,} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
